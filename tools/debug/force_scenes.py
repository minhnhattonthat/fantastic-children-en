"""force_scenes.py: warp scenes that force every message whose pages a tour never showed (text coverage).

    python -X utf8 $SKILL/scripts/textcover.py work/qa/p8/tour build/strings.tsv > work/qa/p8/cover_full.txt
    python -X utf8 tools/debug/force_scenes.py work/qa/p8/cover_full.txt [--pages 40]
    python -X utf8 tools/debug/warp_all.py --scenes tools/debug/force.gba.txt --out work/qa/p8/force \
        --pages 999 --cover build/strings.tsv --jobs 3

Reads the textcover output ("NEVER SHOWN  pXXXXXX ..." lines), picks for every page never shown one message that
holds it (greedy: the message covering most unshown pages first), and writes tools/debug/force.gba.txt: scenes
`force_NN stg=62 ev=21 msg=FIRST force=a,b,..` of about --pages pages each. warp.lua runs the one-message test event
21 and swaps each message fetch for the next id of the list, restarting the event until the list is used up. The
pages show in the event's box (the bottom box: every top-box budget is smaller, so the fit was linted for both).
"""
import argparse
import re
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools"))
import msgs  # noqa: E402

ROM = ROOT / "rom" / "Fantastic Children (Japan).gba"
OUT = ROOT / "tools" / "debug" / "force.gba.txt"
BUS = 0x08000000
BASE = "stg=62 ev=21"   # test event 21: one record, one message (16), no choice
PUT_PER = 60            # system strings per forceput scene (3 per cursor move, 40 frames a move)


def message_pages(rom):
    """message id -> its page ids (pXXXXXX = ROM offset of the page in the original)."""
    out = {}
    for n in range(msgs.MSG_COUNT):
        p = struct.unpack_from("<I", rom, msgs.MSG_TABLE + 4 * n)[0] - BUS
        pages = []
        while True:
            q = struct.unpack_from("<I", rom, p)[0]
            if not q:
                break
            pages.append("p%06X" % (q - BUS))
            p += 4
        out[n] = pages
    return out


def pick(never, pages_of):
    """Greedy cover: messages holding the most unshown pages first; returns ids in message order."""
    left, chosen = set(never), []
    while left:
        best = max(pages_of, key=lambda m: (len(left & set(pages_of[m])), -m))
        got = left & set(pages_of[best])
        if not got:
            break
        chosen.append(best)
        left -= got
    return sorted(chosen), left


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cover", type=Path, help="textcover.py output of the tour")
    ap.add_argument("--pages", type=int, default=40, help="pages per scene (about 90 frames each)")
    a = ap.parse_args()
    never = re.findall(r"^NEVER SHOWN\s+(p[0-9A-F]{6})", a.cover.read_text(encoding="utf-8"), re.M)
    pages_of = message_pages(ROM.read_bytes())
    chosen, left = pick(never, pages_of)
    scenes, cur, n = [], [], 0
    for m in chosen:
        cur.append(m)
        n += len(pages_of[m])
        if n >= a.pages:
            scenes.append(cur)
            cur, n = [], 0
    if cur:
        scenes.append(cur)
    lines = ["# generated by tools/debug/force_scenes.py from a tour's textcover output: messages whose pages no",
             f"# scene showed ({len(never)} pages, {len(chosen)} messages). warp.lua key force= (see there).", ""]
    lines += [f"force_{k + 1:02d}  {BASE} msg={s[0]} force={','.join(map(str, s))}" for k, s in enumerate(scenes)]
    # system strings: forced into the pause info rows (warp.lua forceput=), PUT_PER a scene
    sysn = re.findall(r"^NEVER SHOWN\s+s[0-9A-F]{6}\s+([0-9A-F]+)", a.cover.read_text(encoding="utf-8"), re.M)
    puts = [sysn[k:k + PUT_PER] for k in range(0, len(sysn), PUT_PER)]
    lines += ["", f"# {len(sysn)} system strings no scene read, drawn in the pause info rows (forceput=)"]
    lines += [f"forceput_{k + 1:02d}  stg=16 sub=5 forceput={','.join(s)}" for k, s in enumerate(puts)]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(never)} unshown pages -> {len(chosen)} messages in {len(scenes)} scenes; "
          f"{len(sysn)} system strings in {len(puts)} forceput scenes -> {OUT}")
    if left:
        print(f"{len(left)} pages in no message: {sorted(left)[:10]}")


if __name__ == "__main__":
    main()
