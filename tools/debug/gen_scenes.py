"""gen_scenes.py: write tools/debug/scenes.gba.txt from the ROM's area and event tables (docs/re/events.md).

    python -X utf8 tools/debug/gen_scenes.py

Hand-written scenes (boot screens, menus, endings, staff roll) are the HAND block below; generated ones:
  area_HH     every stage area (stage byte HH = world | area << 4), entered the game's way (entry event plays)
  battle_NN   every event script that starts talk battle NN (first script per battle), in a clean area
  ev_NNNN     every other event script that shows text, by its start record
Each generated event scene carries `msg=` (every message id its script can show): warp_all.py checks the game
fetched one of them.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools"))
from dec import ROM  # noqa: E402
from events import areas, cond, flow_msgs, records, scripts  # noqa: E402

OUT = ROOT / "tools" / "debug" / "scenes.gba.txt"
HAND_EVENTS = (43, 1986, 2311)  # records the HAND scenes run: prologue, endings, debug viewer
# scenes whose screen stays black by design: warp_all checks the message fetch, not the shot
BLANK_OK = {17: "test event セーブきどうイベント: black screen; message 13 is its debug label, never drawn"}
EVENT_AREA = "62"  # indoor area with a plain backdrop; area 16's BG layer garbles the battle screen

HAND = """\
# Scene list for tools/debug/warp.lua (keys in its header). Generated by tools/debug/gen_scenes.py: edit HAND there.
# Stage byte = world | area << 4. Event scenes run the script in area 62 unless they are an area's entry event.
title        boot=title                     # title menu (START GAME / DELETE GAME, already English)
filesel      boot=filesel                   # file select (NEW GAME slots)
prologue     wait=250                       # new game: opening picture-book cutscene (record 43)
pause        stg=16 sub=5                   # pause menu: BATTLE EDIT (battle-item deck)
pause_support stg=16 sub=5 keys=r          # pause: SUPPORT EDIT (L/R switch pages)
pause_items  stg=16 sub=5 keys=r,r          # pause: ITEM INFO
save_prompt  stg=16 sub=11 wait=400         # save point prompt (セーブしますか？)
gameover     mode=9                         # game over screen (stage sub-state 3 leads here after the fall)
# Endings: record 1986 runs 0x08032B60 first, which sets flags 0x85/0x86/0x87 from play time and collectibles
ending_a     ev=1986 full=1 play=500000 msg=976           # > 2 h, items missing (records 1988-2066)
ending_b     ev=1986 full=1 msg=1040                      # cleared within 2 h (flag 0x85, records 2067-2184)
ending_c     ev=1986 full=1 play=500000 allitems=1 msg=1138  # > 2 h, all 75 collectibles (0x87, 2185-2255)
staff        mode=8 wait=900                # staff roll (game mode 8)
debug_viewer ev=2311 full=1                 # leftover character / event-BG viewer script (debug only)
"""


def entry(recs, s, own):
    """(messages the scene can show, ` flags=..`) for a scene starting at record s. A conditional first record
    (f0 > 0 jumps if flag f0 is set, f0 < 0 if flag -f0 is clear) is forced down the branch that reaches the
    script's own text (`own`: messages of records s..e), else the one with any text."""
    """Returns a list of (messages, flags): a second entry when the other branch shows text the first lacks."""
    c = cond(recs[s])
    if not c or not 1 <= abs(c[0]) <= 0x165:
        return [(flow_msgs(recs, s), "")]
    f0 = c[0]
    taken, fall = flow_msgs(recs, s, True), flow_msgs(recs, s, False)
    take = not set(fall) & set(own) and (bool(set(taken) & set(own)) or not fall)

    def flags(t):  # taken: the jump's condition must hold (f0 > 0: flag set); falling through: it must not
        start = c[1] if t else next_rec(recs, s)
        fs = [flag(f0, t)] + (chain(recs, start) if start is not None else [])
        return " flags=" + ",".join(fs)
    first, other = (taken, fall) if take else (fall, taken)
    out = [(first, flags(take))]
    if set(other) - set(first):
        out.append((other, flags(not take)))
    return out


def flag(f0, taken):
    return f"{'' if (f0 > 0) == taken else '-'}{abs(f0):X}"


def next_rec(recs, i):
    nxt = recs[i][16]
    return None if nxt == 0xFFFE else i + 1 if nxt == 0xFFFF else nxt


def chain(recs, i, limit=64):
    """Flags for later conditions on a branch where only one way shows any text (the other ends the script
    silently): without them the scene can run to its end showing nothing (ev_0082b: 0x12A, then 0x12D)."""
    out, seen = [], set()
    while i is not None and i < len(recs) and i not in seen and len(seen) < limit:
        seen.add(i)
        r, c = recs[i], cond(recs[i])
        if r[6] != 0xFFFF or r[7] != 0xFFFF:
            return out  # this record shows text itself: the scene has its message
        if c and 1 <= abs(c[0]) <= 0x165:
            taken, fall = flow_msgs(recs, i, True), flow_msgs(recs, i, False)
            if bool(taken) == bool(fall):
                return out
            out.append(flag(c[0], bool(taken)))
            i = c[1] if taken else next_rec(recs, i)
            continue
        i = next_rec(recs, i)
    return out


def main():
    d = ROM.read_bytes()
    recs = records(d)
    entry_of = {}
    lines = [HAND, "# --- areas"]
    for stg, ev in areas(d):
        lines.append(f"area_{stg:02X}      stg={stg:02X}" + (f"      # entry event {ev}" if ev is not None else ""))
        if ev is not None:
            entry_of.setdefault(ev, f"{stg:02X}")
    lines.append("# --- talk battles (first script per battle id)")
    seen_battle = set()
    evlines = ["# --- event scripts with text"]
    covered = {m for s in HAND_EVENTS for m in flow_msgs(recs, s)}
    for s, e, own, bats, _ in scripts(recs):
        if not own and not bats:
            continue
        stg = next((entry_of[i] for i in range(s, e + 1) if i in entry_of), EVENT_AREA)
        for k, (msgs, flags) in enumerate(entry(recs, s, own)):
            covered.update(msgs)
            # every message the scene's record flow can show: later conditions decide which comes first
            msg = (f" msg={','.join(map(str, msgs))}" if msgs else "") + flags
            new = [b for b in bats if b not in seen_battle] if s >= 37 and k == 0 else []  # 0-36: test events
            if new:
                seen_battle.update(new)
                lines.append(f"battle_{new[0]:02d}    stg={stg} ev={s}{msg}      # battles {','.join(map(str, bats))}")
            else:
                note = f" blank=1      # {BLANK_OK[s]}" if s in BLANK_OK else ""
                evlines.append(f"ev_{s:04d}{'b' if k else ''}      stg={stg} ev={s}{msg}{note}")
    OUT.write_text("\n".join(lines + evlines) + "\n", encoding="utf-8", newline="\n")
    print(f"{OUT}: {len(lines) + len(evlines)} lines, {len(seen_battle)} battle ids")
    shown = {r[6] for r in recs[37:] if r[6] != 0xFFFF}  # +0xC messages outside the 0-36 test events
    left = sorted(shown - covered)
    print(f"{len(shown) - len(left)}/{len(shown)} record messages on some scene's flow; not: {left[:40]}")


if __name__ == "__main__":
    main()
