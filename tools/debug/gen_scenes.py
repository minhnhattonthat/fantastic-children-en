"""gen_scenes.py: write tools/debug/scenes.gba.txt from the ROM's area and event tables (docs/re/events.md).

    python -X utf8 tools/debug/gen_scenes.py

Hand-written scenes (boot screens, menus, endings, staff roll) are the HAND block below; generated ones:
  area_HH     every stage area (stage byte HH = world | area << 4), entered the game's way (entry event plays)
  battle_NN   every event script that starts talk battle NN (first script per battle), in a clean area
  ev_NNNN     every other event script that shows text, by its start record
Each generated event scene carries `msg=` (its first message id): warp_all.py checks the game fetched it.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools"))
from dec import ROM  # noqa: E402
from events import areas, records, scripts  # noqa: E402

OUT = ROOT / "tools" / "debug" / "scenes.gba.txt"
EVENT_AREA = "62"   # indoor area with a plain backdrop; area 16's BG layer garbles the battle screen

HAND = """\
# Scene list for tools/debug/warp.lua (keys in its header). Generated by tools/debug/gen_scenes.py: edit HAND there.
# Stage byte = world | area << 4. Event scenes run the script in area 62 unless they are an area's entry event.
title        boot=title                     # title menu (START GAME / DELETE GAME, already English)
filesel      boot=filesel                   # file select (NEW GAME slots)
prologue     wait=250                       # new game: opening picture-book cutscene (record 43)
pause        stg=16 sub=5                   # pause menu: BATTLE EDIT (battle-item deck)
pause_support stg=16 sub=5 keys=r          # pause: SUPPORT EDIT (L/R switch pages)
pause_items  stg=16 sub=5 keys=r,r          # pause: ITEM INFO
save_prompt  stg=16 sub=11 wait=400         # save point prompt (セーブしますか？)
gameover     mode=9                         # game over screen (stage sub-state 3 leads here after the fall)
# Endings: record 1986 runs 0x08032B60 first, which sets flags 0x85/0x86/0x87 from play time and collectibles
ending_a     ev=1986 full=1 play=500000 msg=976           # > 2 h, items missing (records 1988-2066)
ending_b     ev=1986 full=1 msg=1040                      # cleared within 2 h (flag 0x85, records 2067-2184)
ending_c     ev=1986 full=1 play=500000 allitems=1 msg=1138  # > 2 h, all 75 collectibles (0x87, 2185-2255)
staff        mode=8 wait=900                # staff roll (game mode 8)
debug_viewer ev=2311 full=1                 # leftover character / event-BG viewer script (debug only)
"""


def main():
    d = ROM.read_bytes()
    recs = records(d)
    entry = {}
    lines = [HAND, "# --- areas"]
    for stg, ev in areas(d):
        lines.append(f"area_{stg:02X}      stg={stg:02X}" + (f"      # entry event {ev}" if ev is not None else ""))
        if ev is not None:
            entry.setdefault(ev, f"{stg:02X}")
    lines.append("# --- talk battles (first script per battle id)")
    seen_battle = set()
    evlines = ["# --- event scripts with text"]
    for s, e, msgs, bats, _ in scripts(recs):
        if not msgs and not bats:
            continue
        stg = next((entry[i] for i in range(s, e + 1) if i in entry), EVENT_AREA)
        msg = f" msg={msgs[0]}" if msgs else ""
        new = [b for b in bats if b not in seen_battle] if s >= 37 else []  # 0-36: debug test events
        if new:
            seen_battle.update(new)
            lines.append(f"battle_{new[0]:02d}    stg={stg} ev={s}{msg}      # battles {','.join(map(str, bats))}")
        else:
            evlines.append(f"ev_{s:04d}      stg={stg} ev={s}{msg}")
    OUT.write_text("\n".join(lines + evlines) + "\n", encoding="utf-8", newline="\n")
    print(f"{OUT}: {len(lines) + len(evlines)} lines, {len(seen_battle)} battle ids")


if __name__ == "__main__":
    main()
