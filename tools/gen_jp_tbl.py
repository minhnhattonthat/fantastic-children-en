"""gen_jp_tbl.py: write tbl/jp.tbl (16-bit LE codes) from the font's charset order plus tbl/kanji.txt.

    python -X utf8 tools/gen_jp_tbl.py          # rewrites tbl/jp.tbl

The dialogue font (docs/re/text.md) is in a fixed order: digits, katakana gojuon, voiced, small, A-Z, symbols,
hiragana (= katakana + 0x8E), a-z, then kanji from 0x105. tbl/kanji.txt holds one line per kanji cell,
"105=愛" (a "?" value means not yet read; those codes stay out of the table and decode as hex).
Keys are written in data byte order (low byte first): code 0x0099 -> "9900".
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

KATA = ("アイウエオカキクケコサシスセソタチツテトナニヌネノハヒフヘホマミムメモヤユヨラリルレロワヰヱヲン"
        "ガギグゲゴザジズゼゾダヂヅデドバビブベボパピプペポァィゥェォッャュョ")
HIRA = ("あいうえおかきくけこさしすせそたちつてとなにぬねのはひふへほまみむめもやゆよらりるれろわゐゑをん"
        "がぎぐげござじずぜぞだぢづでどばびぶべぼぱぴぷぺぽぁぃぅぇぉっゃゅょ")
# code -> char for the hand-read cells (docs/re/text.md: "guess" marks)
FIXED = {
    0x000: "\\s",   # blank cell; also the space in strings (verified: 遠くから_なみの at 0x7F23E)
    0x037: "Ⅱ", 0x038: "Ⅲ",  # drawn as roman numerals in the ヰ/ヱ slots (guess: read off the font)
    0x05D: "ヴ",
    0x078: "ー", 0x079: "×", 0x07A: "＝", 0x07B: "：", 0x07C: "？", 0x07D: "＋", 0x07E: "÷", 0x07F: "※",
    0x080: "◆", 0x081: "！", 0x082: "＄", 0x083: "％", 0x084: "＆", 0x085: "、", 0x086: "。", 0x087: "．",
    0x088: "・", 0x089: "；", 0x08A: "’", 0x08B: "”", 0x08C: "～", 0x08D: "／", 0x08E: "（", 0x08F: "）",
    0x090: "「", 0x091: "」", 0x092: "↑", 0x093: "▶", 0x094: "↓", 0x095: "←", 0x096: "◎", 0x097: "▼",
    0x098: "♪", 0x110: "『", 0x111: "』",
}
# control codes: 0x80xx ends a page (low bits = page-end mode); 0x02xx inserts argument (code & 0xFF)
CTRL = {0x8000: "{end}"}
CTRL.update({0x8000 + i: "{end%02X}" % i for i in range(1, 0x17)})


def build():
    m = {}
    for i in range(10):
        m[0x001 + i] = str(i)
    for i, ch in enumerate(KATA):
        code = 0x00B + i
        if code not in (0x037, 0x038):
            m[code] = ch
    for i in range(26):
        m[0x05E + i] = chr(ord("Ａ") + i)
    for i, ch in enumerate(HIRA):
        m[0x099 + i] = ch
    for i in range(26):
        m[0x0EB + i] = chr(ord("ａ") + i)
    m.update(FIXED)
    kfile = ROOT / "tbl" / "kanji.txt"
    if kfile.exists():
        for line in kfile.read_text(encoding="utf-8").splitlines():
            if "=" in line and not line.startswith("#"):
                k, v = line.split("=", 1)
                if v and v != "?":
                    m[int(k, 16)] = v
    lines = ["# generated by tools/gen_jp_tbl.py; edit tbl/kanji.txt or the generator, not this file"]
    for code in sorted(m):
        lines.append(f"{code & 0xFF:02X}{code >> 8:02X}={m[code]}")
    for code, name in sorted(CTRL.items()):
        lines.append(f"{code & 0xFF:02X}{code >> 8:02X}={name}")
    return lines


if __name__ == "__main__":
    out = ROOT / "tbl" / "jp.tbl"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(build()) + "\n", encoding="utf-8")
    print(out)
